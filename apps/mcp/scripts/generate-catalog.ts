import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { buildCatalog, type Specification } from "../src/catalog-builder.ts";

const base = new URL("../", import.meta.url);
const provenance = JSON.parse(await readFile(new URL("spec/provenance.json", base), "utf8"));
const source = await readFile(new URL(`spec/${provenance.file}`, base));
if (createHash("sha256").update(source).digest("hex") !== provenance.sha256) throw new Error("Pinned Apple specification checksum mismatch");
const spec = JSON.parse(source.toString()) as Specification;
if (spec.info.version !== provenance.version) throw new Error("Pinned version mismatch");
const catalog = { version: provenance.version, sha256: provenance.sha256, operations: buildCatalog(spec) };
const generated = `${JSON.stringify(catalog)}\n`;
const target = new URL("src/generated/operations.json", base);
if (process.argv.includes("--check")) {
  if (await readFile(target, "utf8") !== generated) throw new Error("Generated catalog is stale. Run pnpm --filter @asc-mcp/mcp generate:catalog");
} else await writeFile(target, generated);
console.log(`Apple ${catalog.version}: ${catalog.operations.length} operations, ${Buffer.byteLength(generated)} generated bytes`);
